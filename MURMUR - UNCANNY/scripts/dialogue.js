function mergeMurmurNewLines(base, additions) {
 for (const mobId of Object.keys(additions)) {
  if (!base[mobId]) base[mobId] = {};

  for (const category of Object.keys(additions[mobId])) {
   const addValue = additions[mobId][category];

   if (Array.isArray(addValue)) {
    if (!Array.isArray(base[mobId][category])) {
     base[mobId][category] = [];
    }
    base[mobId][category].push(...addValue);
   } else {
    if (typeof base[mobId][category] !== "object" || base[mobId][category] === null) {
     base[mobId][category] = {};
    }

    for (const subKey of Object.keys(addValue)) {
     if (!Array.isArray(base[mobId][category][subKey])) {
      base[mobId][category][subKey] = [];
     }
     base[mobId][category][subKey].push(...addValue[subKey]);
    }
   }
  }
 }
}

